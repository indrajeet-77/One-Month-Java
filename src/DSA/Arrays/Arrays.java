package DSA.Arrays;

public class Arrays {

    public static void main(String[] args) {
//      this is how we initialize the empty array
        int[] numbers = new int[5];

        numbers[0] = 10;
        numbers[1] = 20;
        numbers[2] = 30;

        System.out.println(numbers[0]);
        System.out.println(numbers[1]);
        System.out.println(numbers[2]);
    }
}
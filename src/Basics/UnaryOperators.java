package Basics;
/*
| Operator | Meaning   |
| -------- | --------- |
| ++       | Increment |
| --       | Decrement |

*/

    public class UnaryOperators{
        public static void main (String[] args){

            int i=0;
            i++;
            System.out.println(i);
            i--;
            System.out.println(i);

        }
    }
 
